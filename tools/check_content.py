#!/usr/bin/env python3
"""Check content/site.json statuses and maintain the placeholder register.

Usage:
  python3 tools/check_content.py            # summary; warns on placeholders/needsReview
  python3 tools/check_content.py --register # also (re)write PLACEHOLDERS.md
  FAIL_ON_PLACEHOLDERS=true ...            # exit 1 if any placeholder remains
"""

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "site.json"
REGISTER = ROOT / "docs" / "content-restructure" / "PLACEHOLDERS.md"
HTML_PAGES = [
    "index.html", "services.html", "sectors.html", "how-we-work.html", "about.html",
    "projects.html", "team.html", "credentials.html", "contact.html",
    "privacy.html", "404.html",
]


def flatten(obj, prefix=""):
    out = {}
    for k, v in obj.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict) and "value" in v and "status" in v:
            out[key] = v
        elif isinstance(v, dict):
            out.update(flatten(v, key + "."))
    return out


def slot_pages(key):
    pages = []
    for page in HTML_PAGES:
        path = ROOT / page
        if path.exists() and f"slot:{key}" in path.read_text(encoding="utf-8"):
            pages.append(page)
    return ", ".join(pages) if pages else "(unused)"


def main():
    data = json.loads(CONTENT.read_text(encoding="utf-8"))
    slots = flatten(data)
    placeholders = {k: v for k, v in slots.items() if v["status"] == "placeholder"}
    needs_review = {k: v for k, v in slots.items() if v.get("needsReview")}
    confirmed = sum(1 for v in slots.values() if v["status"] == "confirmed")
    derived = sum(1 for v in slots.values() if v["status"] == "derived")

    print(f"check_content: {len(slots)} slots — "
          f"{confirmed} confirmed, {derived} derived, "
          f"{len(placeholders)} placeholder, {len(needs_review)} needsReview")

    if placeholders:
        print("\nPlaceholders:")
        for key in sorted(placeholders):
            item = placeholders[key]
            print(f"  {key}  [{item.get('source', '?')}]  via {slot_pages(key)}")

    noted = {k: v for k, v in slots.items() if v.get("note")}
    if noted:
        print(f"\nReview notes ({len(noted)}):")
        for key in sorted(noted):
            print(f"  {key}: {noted[key]['note']}")

    if "--register" in sys.argv:
        REGISTER.parent.mkdir(parents=True, exist_ok=True)
        lines = [
            "# Placeholder register",
            "",
            "> Generated by `python3 tools/check_content.py --register`. "
            "Edit `content/site.json`, not this file.",
            "",
            "| Content key | Page / component | File path | Questionnaire ref | Notes |",
            "|---|---|---|---|---|",
        ]
        for key in sorted(placeholders):
            item = placeholders[key]
            lines.append(
                f"| `{key}` | {slot_pages(key)} | `content/site.json` | "
                f"{item.get('source', '?')} | value: “{item['value'][:60]}” |"
            )
        lines.append("")
        if noted:
            lines.append("## Review notes (non-placeholder slots)")
            lines.append("")
            lines.append("| Content key | Note |")
            lines.append("|---|---|")
            for key in sorted(noted):
                lines.append(f"| `{key}` | {noted[key]['note']} |")
            lines.append("")
        REGISTER.write_text("\n".join(lines), encoding="utf-8")
        print(f"\nregister written: {REGISTER.relative_to(ROOT)} ({len(placeholders)} entries)")

    if os.environ.get("FAIL_ON_PLACEHOLDERS") == "true" and placeholders:
        print("\nFAIL_ON_PLACEHOLDERS=true — failing.")
        sys.exit(1)


if __name__ == "__main__":
    main()
